"""Check/rebuild the export-safe shader source index (Python standard library only).

Authoring inputs: library/catalog.json plus standalone .gdshader files.
Runtime uses a preloaded GDScript constant so Godot exports need no JSON filter,
FileAccess-to-imported-resource workaround, or eager compilation of 162 shaders.
"""
from pathlib import Path
import argparse
import hashlib
import json


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Rebuild the generated runtime index")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    library = root / "Workspaces/ShaderWorkspace/library"
    entries = json.loads((library / "catalog.json").read_text(encoding="utf-8"))
    for entry in entries:
        relative = entry["path"].removeprefix("res://")
        source_path = root / relative
        source_bytes = source_path.read_bytes()
        assert hashlib.sha256(source_bytes).hexdigest() == entry["source_sha256"], relative
        entry["source"] = source_bytes.decode("utf-8")
    generated = (
        "extends RefCounted\n"
        "## Generated by scripts/tests/rebuild_shader_library_index.py --write.\n"
        "## Immutable source strings ensure previews/open/save work in exported applications.\n"
        "const ENTRIES: Array[Dictionary] = "
        + json.dumps(entries, indent=2, ensure_ascii=False)
        + "\n"
    )
    destination = library / "shader_library_data.gd"
    if args.write:
        destination.write_text(generated, encoding="utf-8", newline="\n")
    elif not destination.exists() or destination.read_text(encoding="utf-8") != generated:
        raise SystemExit("Runtime shader index is stale; regenerate with --write.")
    print(f"Shader index verified: {len(entries)} complete sources and matching SHA-256 hashes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
