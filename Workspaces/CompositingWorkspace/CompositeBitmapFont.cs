    public static Image Render(Vector2I size, string text, int fontSize, Color color)
    {
        byte[] pixels = new byte[checked(size.X * size.Y * 4)]; int scale = Math.Max(1, fontSize / 7), penX = 2;
        foreach (char character in text.Substring(0, Math.Min(128, text.Length)).ToUpperInvariant())
        {
            string[] glyph = Patterns.TryGetValue(character, out var found) ? found : Patterns['?'];
            if (penX + 5 * scale > size.X) break;
            for (int row = 0; row < 7; row++) for (int column = 0; column < 5; column++)
            {
                if (glyph[row][column] != '1') continue;
                for (int y = row * scale + 2; y < Math.Min(size.Y, (row + 1) * scale + 2); y++)
                for (int x = penX + column * scale; x < Math.Min(size.X, penX + (column + 1) * scale); x++)
                {
                    int index = (y * size.X + x) * 4; pixels[index] = (byte)color.R8; pixels[index + 1] = (byte)color.G8; pixels[index + 2] = (byte)color.B8; pixels[index + 3] = (byte)color.A8;
                }
            }
            penX += 6 * scale;
        }
        return Image.CreateFromData(size.X, size.Y, false, Image.Format.Rgba8, pixels);
    }
